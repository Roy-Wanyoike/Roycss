interface ProjectWrapper {
  components: StudioComponent[];
  seedUpdatedAt: string;
  seedCreatedAt: string;
}

function toDbRow(p: StudioProject) {
  const wrapper: ProjectWrapper = {
    components: p.components,
    seedUpdatedAt: p.updatedAt,
    seedCreatedAt: p.createdAt,
  };
  return {
    id: p.id,
    userId: null,
    name: p.name,
    description: p.description,
    filesJson: JSON.stringify(wrapper),
  };
}

function toDomain(row: {
  id: string;
  name: string;
  description: string;
  filesJson: string;
  createdAt: Date;
  updatedAt: Date;
}): StudioProject {
  let wrapper: ProjectWrapper = {
    components: [],
    seedUpdatedAt: row.updatedAt.toISOString(),
    seedCreatedAt: row.createdAt.toISOString(),
  };
  try {
    wrapper = JSON.parse(row.filesJson) as ProjectWrapper;
  } catch {
    // Keep defaults.
  }
  return {
    id: row.id,
    name: row.name,
    description: row.description,
    components: wrapper.components,
    updatedAt: wrapper.seedUpdatedAt,
    createdAt: wrapper.seedCreatedAt,
  };
}

let seedPromise: Promise<void> | null = null;
async function seedIfEmpty(): Promise<void> {
  if (seedPromise) return seedPromise;
  seedPromise = (async () => {
    const count = await db.studioProject.count();
    if (count === 0) {
      await db.studioProject.createMany({
        data: SEED_PROJECTS.map(toDbRow),
      });
      log.info("Studio projects seeded", { count: SEED_PROJECTS.length });
    }
  })().catch((err) => {
    seedPromise = null;
    throw err;
  });
  return seedPromise;
}

/** List all studio projects. Cached. */
export async function listProjects(): Promise<StudioProject[]> {
  return cacheWrap(
    PROJECTS_KEY,
    async () => {
      await seedIfEmpty();
      const rows = await db.studioProject.findMany({
        orderBy: { createdAt: "asc" },
      });
      return rows.map(toDomain);
    },
    CACHE_TTL.studioProjects,
  );
}

/** Get a single studio project by id. Cached. Throws 404 if missing. */
export async function getProjectById(id: string): Promise<StudioProject> {
  return cacheWrap(
    detailKey(id),
    async () => {
      await seedIfEmpty();
      const row = await db.studioProject.findUnique({ where: { id } });
      if (!row) throw AppError.notFound(`Studio project '${id}' not found`);
      return toDomain(row);
    },
    CACHE_TTL.studioProjectDetail,
  );
}

/** Create a new studio project. Invalidates list cache. */
export async function createProject(
  input: CreateStudioProjectInput,
): Promise<StudioProject> {
  const now = new Date().toISOString();
  const project: StudioProject = {
    id: `studio-proj-${randomUUID()}`,
    name: input.name,
    description: input.description,
    components: input.components,
    updatedAt: now,
    createdAt: now,
  };
  await db.studioProject.create({ data: toDbRow(project) });
  invalidate(project.id);
  log.info("Studio project created", { id: project.id, name: project.name });
  return project;
}

/** Update an existing studio project (partial). Invalidates caches. */
export async function updateProject(
  id: string,
  input: UpdateStudioProjectInput,
): Promise<StudioProject> {
  await seedIfEmpty();
  const row = await db.studioProject.findUnique({ where: { id } });
  if (!row) throw AppError.notFound(`Studio project '${id}' not found`);
  let wrapper: ProjectWrapper;
  try {
    wrapper = JSON.parse(row.filesJson) as ProjectWrapper;
  } catch {
    wrapper = { components: [], seedUpdatedAt: row.updatedAt.toISOString(), seedCreatedAt: row.createdAt.toISOString() };
  }
  const updatedName = input.name ?? row.name;
  const updatedDescription = input.description ?? row.description;
  const updatedComponents = input.components ?? wrapper.components;
  const now = new Date().toISOString();
  const updatedWrapper: ProjectWrapper = {
    components: updatedComponents,
    seedUpdatedAt: now,
    seedCreatedAt: wrapper.seedCreatedAt,
  };
  await db.studioProject.update({
    where: { id },
    data: {
      name: updatedName,
      description: updatedDescription,
      filesJson: JSON.stringify(updatedWrapper),
    },
  });
  invalidate(id);
  log.info("Studio project updated", { id });
  return toDomain({
    ...row,
    name: updatedName,
    description: updatedDescription,
    filesJson: JSON.stringify(updatedWrapper),
    updatedAt: new Date(),
  });
}

/** Delete a studio project by id. Invalidates caches. */
export async function deleteProject(id: string): Promise<void> {
  await seedIfEmpty();
  const row = await db.studioProject.findUnique({ where: { id } });
  if (!row) throw AppError.notFound(`Studio project '${id}' not found`);
  await db.studioProject.delete({ where: { id } });
  invalidate(id);
  log.info("Studio project deleted", { id });
}

/** List all studio starter templates. Cached. */
