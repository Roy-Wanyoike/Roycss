/**
 * Studio service — Prisma-backed Roy Studio visual-builder project store.
 *
 * Persisted via the Prisma `StudioProject` model. Seeds 4 studio
 * projects (each with a components tree) on first access. Starter
 * templates remain a static in-memory seed (no Prisma model).
 *
 * Field-mapping: the Prisma `StudioProject` model exposes (userId,
 * name, description, filesJson). The domain shape's `name`,
 * `description` map directly; the components tree is JSON-encoded
 * inside `filesJson`; (updatedAt, createdAt) are mirrored via the
 * Prisma `updatedAt`/`createdAt` columns.
 *
 * Note: the original seed used stable IDs (e.g. `studio-proj-landing-page`)
 * generated by `randomUUID()` *at module-load time* — we instead pin
 * the seed IDs to deterministic slugs so DB rows are stable across
 * server restarts.
 */
